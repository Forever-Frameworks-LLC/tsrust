#!/usr/bin/env python3
"""Generate the std:ui GPUI Kit wrappers and their IntelliSense entries.

The single source is crates/tsrust-compiler/src/stdlib/ui/kit.json. This writes
crates/tsrust-compiler/src/stdlib/ui/kit.tsr (typed component functions over the
generic kit node) and merges one entry per component and props interface into
the "std:ui" list of crates/tsrust-lsp/src/builtins.json. The GPUI renderer arms
in stdlib/ui/gpui.rs are written by hand against the same names.

usage: generate-ui-kit.py [--check]
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "crates/tsrust-compiler/src/stdlib/ui/kit.json"
OUTPUT = ROOT / "crates/tsrust-compiler/src/stdlib/ui/kit.tsr"
BUILTINS = ROOT / "crates/tsrust-lsp/src/builtins.json"
ICONS = ROOT / "crates/tsrust-compiler/src/stdlib/ui/gpui_icons.rs"

HEADER = """
// Generated by tools/generate-ui-kit.py from kit.json. Do not edit.
import { kit as nativeKit, kitValue as nativeKitValue, kitSet as nativeKitSet, kitBind as nativeKitBind, kitOn as nativeKitOn, kitOnBoolean as nativeKitOnBoolean, kitOnInt as nativeKitOnInt, kitOnNumber as nativeKitOnNumber, kitOnVoid as nativeKitOnVoid } from 'std:ui-runtime';

function kitNode(name: string, children: Child[], className: string): Node {
  return unwrapNode(nativeKit(children, className, name));
}

function kitFlag(node: Node, name: string, value: ReactiveValue<boolean>): Node {
  if (typeof value === 'boolean') {
    return unwrapNode(nativeKitSet(node, name, value ? 'true' : 'false'));
  }
  return unwrapNode(nativeKitBind(node, name, nativeBindText(value.evaluate)));
}

function kitNumber(node: Node, name: string, value: ReactiveValue<number>): Node {
  if (typeof value === 'number') {
    const constant = value;
    return unwrapNode(nativeKitBind(node, name, nativeBindText(() => constant)));
  }
  return unwrapNode(nativeKitBind(node, name, nativeBindText(value.evaluate)));
}

function kitInt(node: Node, name: string, value: ReactiveValue<int>): Node {
  if (typeof value === 'number') {
    const constant = value;
    return unwrapNode(nativeKitBind(node, name, nativeBindText(() => constant)));
  }
  return unwrapNode(nativeKitBind(node, name, nativeBindText(value.evaluate)));
}
"""

SCALAR = {"string": ("ReactiveValue<string> | TextBinding", "kitValue"), "boolean": ("ReactiveValue<boolean>", "kitFlag"),
          "int": ("ReactiveValue<int>", "kitInt"), "number": ("ReactiveValue<number>", "kitNumber")}
EVENTS = {"void": ("Owned<Function<void>>", "nativeKitOnVoid", None),
          "boolean": ("Owned<Function<void, [{param}: boolean]>>", "nativeKitOnBoolean", "boolean"),
          "int": ("Owned<Function<void, [{param}: int]>>", "nativeKitOnInt", "int"),
          "number": ("Owned<Function<void, [{param}: number]>>", "nativeKitOnNumber", "number"),
          "string": ("Owned<Function<void, [{param}: ReadOnly<string>]>>", "nativeKitOn", "string")}


def event_name(prop):
    return prop[2].lower() + prop[3:] if prop.startswith("on") else prop


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def icon_source(icons):
    arms = "\n".join(f'        "{name}" => IconName::{pascal(name)},' for name in icons)
    return f"""// Generated by tools/generate-ui-kit.py from kit.json. Do not edit.
use gpui_kit::component::IconName;

/// The GPUI Kit icon for a std:ui icon name.
fn icon_name(name: &str) -> Option<IconName> {{
    Some(match name {{
{arms}
        _ => return None,
    }})
}}
"""


def prop_type(prop):
    kind = prop["type"]
    if kind == "icon":
        return "ReactiveValue<IconName>"
    if isinstance(kind, list):
        literal = " | ".join(f"'{value}'" for value in kind)
        return f"ReactiveValue<{literal}>"
    if kind in ("string[]", "number[]", "string[][]"):
        return kind
    return SCALAR[kind][0]


def event_type(event):
    return EVENTS[event["value"]][0].format(param=event.get("param", "value"))


def has_children(component):
    return bool(component.get("children"))


def children_doc(component):
    children = component.get("children")
    if children is True:
        return "Content shown inside the component."
    if isinstance(children, str):
        return f"{children} elements."
    return None


def component_source(component):
    name = component["name"]
    lines = [f"export interface {name}Props {{"]
    for prop in component.get("props", []):
        lines.append(f"  /** {prop['doc']} */")
        lines.append(f"  {prop['name']}?: {prop_type(prop)};")
    for event in component.get("events", []):
        lines.append(f"  /** {event['doc']} */")
        lines.append(f"  {event['prop']}?: {event_type(event)};")
    if has_children(component):
        lines.append(f"  /** {children_doc(component)} */")
        lines.append("  children?: Child[];")
    lines.append("  /** Shared utility classes applied around the component, such as width or margin. */")
    lines.append("  className?: string;")
    lines.append("}")
    lines.append("")
    lines.append(f"/** {component['doc']} */")
    lines.append(f"export function {name}(props: {name}Props): Node {{")
    children = "props.children ?? []" if has_children(component) else "[]"
    lines.append(f"  let node = kitNode('{name}', {children}, props.className ?? '');")
    for prop in component.get("props", []):
        field = prop["name"]
        local = f"prop_{field}"
        lines.append(f"  const {local} = props.{field};")
        kind = prop["type"]
        if isinstance(kind, list) or kind == "icon":
            lines.append(f"  if ({local} !== undefined) {{")
            lines.append(f"    if (typeof {local} === 'string') {{ node = unwrapNode(nativeKitSet(node, '{field}', `${{{local}}}`)); }}")
            lines.append(f"    else {{ node = unwrapNode(nativeKitBind(node, '{field}', nativeBindText({local}.evaluate))); }}")
            lines.append("  }")
        elif kind == "string[][]":
            lines.append(f"  if ({local} !== undefined) {{ node = unwrapNode(nativeKitSet(node, '{field}', JSON.stringify({local}))); }}")
        elif kind in ("string[]", "number[]"):
            lines.append(f"  if ({local} !== undefined) {{ node = unwrapNode(nativeKitSet(node, '{field}', {local}.join('\\n'))); }}")
        elif kind == "string":
            lines.append(f"  if ({local} !== undefined) {{ node = unwrapNode(nativeKitValue(node, '{field}', {local})); }}")
        else:
            lines.append(f"  if ({local} !== undefined) {{ node = {SCALAR[kind][1]}(node, '{field}', {local}); }}")
    for event in component.get("events", []):
        field = event["prop"]
        local = f"event_{field}"
        binding = EVENTS[event["value"]][1]
        lines.append(f"  const {local} = props.{field};")
        lines.append(f"  if ({local} !== undefined) {{ node = unwrapNode({binding}(node, '{event_name(field)}', {local})); }}")
    lines.append("  return node;")
    lines.append("}")
    return "\n".join(lines)


def documentation(component):
    parts = [component["doc"]]
    props = [f"- `{prop['name']}`: {prop['doc']}" for prop in component.get("props", [])]
    props += [f"- `{event['prop']}`: {event['doc']}" for event in component.get("events", [])]
    if has_children(component):
        props.append(f"- `children`: {children_doc(component)}")
    props.append("- `className`: shared utility classes applied around the component.")
    parts.append("Props:\n" + "\n".join(props))
    parts.append(f"```tsrx\n{component['example']}\n```")
    parts.append("Live props refresh after each handler when their expression reads state. Rendered with GPUI Kit on desktop.")
    parts.append("Ownership: consumes its props and children; handlers are owned by the returned Node.")
    return "\n\n".join(parts)


def entries(component):
    name = component["name"]
    doc = documentation(component)
    return [
        {"name": name, "signature": f"{name}(props: {name}Props): Node",
         "parameters": [{"label": f"props: {name}Props", "documentation": "Component props; every prop is optional."}],
         "documentation": doc},
        {"name": f"{name}Props", "signature": f"interface {name}Props", "documentation": doc},
    ]


def formatted(source):
    """Format like the project formatter; TSRUST selects the compiler (default: target/debug/tsrust)."""
    compiler = os.environ.get("TSRUST", str(ROOT / "target/debug/tsrust"))
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "kit.tsr"
        path.write_text(source)
        subprocess.run([compiler, "format", "--write", str(path)], check=True, stdout=subprocess.DEVNULL)
        return path.read_text()


def main():
    check = "--check" in sys.argv[1:]
    spec = json.loads(SPEC.read_text())
    components = spec["components"]
    icons = spec["icons"]
    names = " | ".join(f"'{name}'" for name in icons)
    icon_type = f"/** A GPUI Kit (Lucide) icon name. */\nexport type IconName = {names};\n"
    source = formatted(HEADER + "\n" + icon_type + "\n" + "\n\n".join(component_source(component) for component in components) + "\n")
    icon_rust = icon_source(icons)
    builtins = json.loads(BUILTINS.read_text())
    generated = [entry for component in components for entry in entries(component)]
    names = {entry["name"] for entry in generated}
    current = builtins.get("std:ui", [])
    merged = [entry for entry in current if entry["name"] not in names] + generated
    builtins["std:ui"] = merged
    rendered = json.dumps(builtins, indent=2, ensure_ascii=False) + "\n"
    stale = []
    existing = OUTPUT.read_text() if OUTPUT.exists() else None
    if existing != source:
        stale.append(OUTPUT)
    if BUILTINS.read_text() != rendered:
        stale.append(BUILTINS)
    if not ICONS.exists() or ICONS.read_text() != icon_rust:
        stale.append(ICONS)
    if check:
        if stale:
            sys.exit("Generated UI Kit files are stale: " + ", ".join(str(path.relative_to(ROOT)) for path in stale))
        return
    OUTPUT.write_text(source)
    ICONS.write_text(icon_rust)
    BUILTINS.write_text(rendered)
    print(f"Generated {len(components)} components")


if __name__ == "__main__":
    main()
