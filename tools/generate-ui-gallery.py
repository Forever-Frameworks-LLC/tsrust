#!/usr/bin/env python3
"""Generate the GPUI Kit component gallery in examples/gpui-starter.

examples/gpui-starter/pages.spec mirrors GPUI Kit's component docs. Each page:

    === Title | slug | Group
    One-paragraph summary.
    --- Section title
    Section description (optional, until the example).
    interface Row { ... }        (optional interfaces and helpers)
    function SectionExample(): Node {
      ...
    }

Every section's function is both rendered live and shown as copyable code.
Writes src/pages/<Title>.tsrx per page and src/main.tsrx (sidebar and routes).
`--check` reports stale files instead of writing them.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STARTER = ROOT / "examples/gpui-starter"
SPEC = STARTER / "pages.spec"
API = [ROOT / "crates/tsrust-compiler/src/stdlib/ui/api.tsr", ROOT / "crates/tsrust-compiler/src/stdlib/ui/kit.tsr"]
ICONS = ROOT / "crates/tsrust-compiler/src/stdlib/ui/gpui_icons.rs"
# The guides are the single source for the gallery's Getting started pages; ```tsx live Name``` blocks run live.
GUIDES = sorted((ROOT / "docs/guides/ui").glob("*.md")) + [ROOT / "docs/guides/tooling/desktop-apps.md"]


def guides():
    """Each guide becomes a page: Markdown blocks between live examples, which compile into the gallery."""
    pages = []
    for index, path in enumerate(GUIDES):
        text = path.read_text()
        title = re.match(r"# (.+)", text).group(1).strip()
        if path.name == "desktop-apps.md":
            title = "Packaging"
        body = re.sub(r"^# .+\n", "", text, count=1).strip()
        blocks = []
        for part in re.split(r"(```tsx live \w+\n.*?```)", body, flags=re.S):
            live = re.match(r"```tsx live (\w+)\n(.*?)```", part, re.S)
            if live:
                blocks.append(("live", live.group(1), live.group(2).rstrip()))
            elif part.strip():
                blocks.append(("markdown", "", part.strip()))
        slug = "" if index == 0 else re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
        pages.append({"title": title, "slug": slug, "blocks": blocks, "source": str(path.relative_to(ROOT))})
    return pages


def guide_source(guide, names):
    code = "\n\n".join(block[2] for block in guide["blocks"] if block[0] == "live")
    used = sorted(names & set(re.findall(r"\b([A-Za-z_]\w*)\b", code)) | {"View", "Node", "Markdown"})
    lines = [
        f"// Generated by tools/generate-ui-gallery.py from {guide['source']}. Do not edit.",
        f"import {{ {', '.join(used)} }} from 'std:ui';",
        "import { LiveExample } from '../example.tsrx';",
        "",
        code,
        "",
        f"export function {component(guide['title'])}(): Node {{",
        "  return (",
        '    <View className="flex-col gap-6">',
        f'      <Markdown content={{{literal("# " + guide["title"])}}} />',
    ]
    for kind, name, text in guide["blocks"]:
        if kind == "live":
            lines.append(f"      <LiveExample code={literal(text)}><{name} /></LiveExample>")
        else:
            lines.append(f"      <Markdown content={{{literal(text)}}} />")
    lines += ["    </View>", "  );", "}", ""]
    return "\n".join(lines)


def check_icons(pages):
    """Icon names are plain strings, so a typo renders nothing; reject unknown literal names."""
    known = set(re.findall(r'^\s+"([a-z0-9-]+)" => IconName::', ICONS.read_text(), re.M))
    for page in pages:
        for section in page["sections"]:
            for use in re.finditer(r'(?:\bicon|\bcheckIcon|<Icon name)="([^"]+)"', section["code"]):
                if use.group(1) not in known:
                    sys.exit(f"{page['title']} / {section['title']}: unknown icon {use.group(1)!r}")


def exports():
    names = set()
    for path in API:
        names.update(re.findall(r"^export (?:function|type|interface) (\w+)", path.read_text(), re.M))
    return names


def parse():
    pages = []
    page = section = None
    for line in SPEC.read_text().splitlines():
        if line.startswith("=== "):
            title, slug, group = [part.strip() for part in line[4:].split("|")]
            page = {"title": title, "slug": slug, "group": group, "summary": [], "sections": []}
            pages.append(page)
            section = None
        elif line.startswith("--- "):
            section = {"title": line[4:].strip(), "text": [], "code": []}
            page["sections"].append(section)
        elif section is None:
            if page is not None and line.strip():
                page["summary"].append(line.strip())
        elif section["code"] or line.startswith(("function ", "interface ")):
            section["code"].append(line)
        elif line.strip():
            section["text"].append(line.strip())
    for page in pages:
        for section in page["sections"]:
            code = "\n".join(section["code"]).rstrip()
            # The example is the section's last function; interfaces and helpers may precede it.
            names = re.findall(r"^function (\w+)\(", code, re.M)
            if not names:
                sys.exit(f"{page['title']} / {section['title']}: the example must define `function Name(): Node`")
            section["code"], section["name"] = code, names[-1]
    return pages


def literal(text):
    return json.dumps(text, ensure_ascii=False)


def component(name):
    return re.sub(r"\W", "", name) + "Page"


def page_source(page, names):
    code = "\n\n".join(section["code"] for section in page["sections"])
    used = sorted(names & set(re.findall(r"\b([A-Za-z_]\w*)\b", code)) | {"View", "Text", "Node"})
    lines = [
        "// Generated by tools/generate-ui-gallery.py from pages.spec. Do not edit.",
        f"import {{ {', '.join(used)} }} from 'std:ui';",
        "import { Example, PageHeader } from '../example.tsrx';",
        "",
        code,
        "",
        f"export function {component(page['title'])}(): Node {{",
        "  return (",
        '    <View className="flex-col gap-10">',
        f"      <PageHeader summary={literal(' '.join(page['summary']))} slug={literal(page['slug'])} />",
    ]
    for section in page["sections"]:
        lines.append(f"      <Example title={literal(section['title'])} description={literal(' '.join(section['text']))} code={literal(section['code'])}><{section['name']} /></Example>")
    lines += ["    </View>", "  );", "}", ""]
    return "\n".join(lines)


