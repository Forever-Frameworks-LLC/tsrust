def search_source(pages, docs):
    """The gallery's search index: one entry per page and per example, with concept keywords."""
    concepts = {}
    for words, slugs in CONCEPTS.items():
        for slug in slugs:
            concepts.setdefault(slug, []).extend(words.split())
    lines = [
        "// Generated by tools/generate-ui-gallery.py from pages.spec. Do not edit.",
        "",
        "/** One searchable page or example. */",
        "export interface SearchEntry {",
        "  route: string;",
        "  page: string;",
        "  section: string;",
        "  text: string;",
        "  keywords: string;",
        "}",
        "",
        "/** Every page and example the gallery search ranks. */",
        "export function searchEntries(): SearchEntry[] {",
        "  return [",
    ]
    def entry(route, page, section, text, keywords):
        lines.append(f"    {{ route: {literal(route)}, page: {literal(page)}, section: {literal(section)}, text: {literal(text.lower())}, keywords: {literal(keywords.lower())} }},")
    for page in pages:
        route = "/" + page["slug"]
        used = sorted(set(re.findall(r"<([A-Z]\w+)", "\n".join(section["code"] for section in page["sections"]))))
        keywords = " ".join([page["slug"].replace("-", " "), *concepts.get(page["slug"], []), *used])
        entry(route, page["title"], "", " ".join(page["summary"]), keywords)
        for section in page["sections"]:
            names = sorted(set(re.findall(r"<([A-Z]\w+)", section["code"])) | set(re.findall(r"\b([a-z][A-Za-z]+)=", section["code"])))
            entry(route, page["title"], section["title"], " ".join(section["text"]), " ".join(names))
    for guide in docs:
        text = " ".join(block[2] for block in guide["blocks"] if block[0] == "markdown")
        entry("/" + guide["slug"], guide["title"], "", re.sub(r"[`#*]", "", text)[:600], "guide docs " + guide["title"])
        for heading in re.findall(r"^## (.+)$", text, re.M):
            entry("/" + guide["slug"], guide["title"], heading, "", "guide docs")
    lines += ["  ];", "}", ""]
    return "\n".join(lines)


def main_source(pages, docs):
    groups = {}
    for page in pages:
        groups.setdefault(page["group"], []).append(page)
    lines = [
        "// Generated by tools/generate-ui-gallery.py from pages.spec. Do not edit.",
        "import { View, Text, Node, Child, signal, run, location, navigate, registerThemes, useTheme, Route, Sidebar, SidebarGroup, SidebarItem, ScrollArea, Button, TitleBar } from 'std:ui';",

        "import { Search } from './search.tsrx';",
        "import { ShowcasePage } from './showcase.tsrx';",
        "import gruvbox from './themes/gruvbox.json';",
    ]
    for page in docs + pages:
        lines.append(f"import {{ {component(page['title'])} }} from './pages/{page['title'].replace(' ', '').replace(',', '')}.tsrx';")
    lines += [
        "",
        "interface PageProps {",
        "  children?: Child[];",
        "}",
        "",
        "function Page(props: PageProps): Node {",
        "  return (",
        '    <ScrollArea className="grow">',
        '      <View className="flex-col p-8 max-w-[960px]" children={props.children ?? []} />',
        "    </ScrollArea>",
        "  );",
        "}",
        "",
        "function App(): Node {",
        "  const path = location();",
        "  const dark = signal(false);",
        "  return (",
        '    <View className="flex-col size-full">',
        "      <TitleBar>",
        '        <Text className="font-semibold">GPUI Kit for Tsrust</Text>',
        '        <View className="grow" />',
        "        <Search />",
        '        <View className="pr-2 pl-1">',
        "          <Button size=\"small\" compact={true} icon={dark.get() ? 'sun' : 'moon'} tooltip=\"Toggle color theme\" aria-label=\"Toggle color theme\" toggled={dark.get()} onPress={() => { dark.set(!dark.get()); useTheme(dark.get() ? 'Gruvbox Dark Medium' : 'Gruvbox Light Medium'); }} />",
        "        </View>",
        "      </TitleBar>",
        '      <View className="flex-row grow min-h-0">',
        "      <Sidebar>",
        '        <SidebarGroup label="Getting started">',
    ]
    for page in docs:
        route = f"/{page['slug']}"
        lines.append(f"          <SidebarItem label={literal(page['title'])} active={{path.get() === {literal(route)}}} onClick={{() => {{ navigate({literal(route)}); }}}} />")
    lines += [
        "          <SidebarItem label=\"Showcase\" active={path.get() === '/showcase'} onClick={() => { navigate('/showcase'); }} />",
        "        </SidebarGroup>",
    ]
    for group, members in groups.items():
        lines.append(f"        <SidebarGroup label={literal(group)}>")
        for page in members:
            route = f"/{page['slug']}"
            lines.append(f"          <SidebarItem label={literal(page['title'])} active={{path.get() === {literal(route)}}} onClick={{() => {{ navigate({literal(route)}); }}}} />")
        lines.append("        </SidebarGroup>")
    lines += [
        "      </Sidebar>",
        '      <View className="flex-col grow min-w-0">',
    ]
    for page in docs:
        lines.append(f"        <Route path={literal('/' + page['slug'])} render={{() => <Page><{component(page['title'])} /></Page>}} />")
    lines.append("        <Route path=\"/showcase\" render={() => <Page><ShowcasePage /></Page>} />")
    lines += [
    ]
    # Each route owns its scroll area, so navigation starts at the top of the page.
    for page in pages:
        lines.append(f"        <Route path={literal('/' + page['slug'])} render={{() => <Page><{component(page['title'])} /></Page>}} />")
    lines += [
        "      </View>",
        "      </View>",
        "    </View>",
        "  );",
        "}",
        "",
        "function main() {",
        "  registerThemes(gruvbox);",
        "  useTheme('Gruvbox Light Medium');",
        "  unwrap(run(App(), 'GPUI Kit for Tsrust', {",
        "    width: 1280, height: 860, minWidth: 800, minHeight: 560, titlebar: 'custom'",
        "  }));",
        "}",
        "",
    ]
    return "\n".join(lines)


def formatted(files):
    """Format like the project formatter (TSRUST selects the compiler)."""
    compiler = os.environ.get("TSRUST", str(ROOT / "target/debug/tsrust"))
    with tempfile.TemporaryDirectory() as directory:
        for name, text in files.items():
            path = Path(directory) / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        subprocess.run([compiler, "format", directory], check=True, stdout=subprocess.DEVNULL)
        return {name: (Path(directory) / name).read_text() for name in files}


def main():
    check = "--check" in sys.argv[1:]
    pages = parse()
    check_icons(pages)
    names = exports()
    files = {f"src/pages/{page['title'].replace(' ', '').replace(',', '')}.tsrx": page_source(page, names) for page in pages}
    docs = guides()
    for guide in docs:
        files[f"src/pages/{guide['title'].replace(' ', '').replace(',', '')}.tsrx"] = guide_source(guide, names)
    files["src/main.tsrx"] = main_source(pages, docs)
    files["src/search-index.tsr"] = search_source(pages, docs)
    files = formatted(files)
    current = {str(path.relative_to(STARTER)) for path in (STARTER / "src/pages").glob("*.tsrx")}
    stale = [name for name, text in files.items() if not (STARTER / name).exists() or (STARTER / name).read_text() != text]
    removed = sorted(current - set(files))
    if check:
        if stale or removed:
            sys.exit("Generated gallery files are stale: " + ", ".join(stale + removed))
        return
    for name, text in files.items():
        path = STARTER / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    for name in removed:
        (STARTER / name).unlink()
    print(f"Generated {len(pages)} pages, {sum(len(page['sections']) for page in pages)} examples")


if __name__ == "__main__":
    main()
