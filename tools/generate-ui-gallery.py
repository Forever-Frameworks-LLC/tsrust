#!/usr/bin/env python3
"""Generate the GPUI Kit component gallery in examples/gpui-starter.

examples/gpui-starter/pages.spec mirrors GPUI Kit's component docs. Each page:

    === Title | slug | Group
    One-paragraph summary.
    --- Section title
    Section description (optional, until the example).
    function SectionExample(): Node {
      ...
    }

Every section's function is both rendered live and shown as copyable code.
Writes src/pages/<Title>.tsrx per page and src/main.tsrx (sidebar and routes).
`--check` reports stale files instead of writing them.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STARTER = ROOT / "examples/gpui-starter"
SPEC = STARTER / "pages.spec"
API = [ROOT / "crates/tsrust-compiler/src/stdlib/ui/api.tsr", ROOT / "crates/tsrust-compiler/src/stdlib/ui/kit.tsr"]


def exports():
    names = set()
    for path in API:
        names.update(re.findall(r"^export (?:function|type|interface) (\w+)", path.read_text(), re.M))
    return names


def parse():
    pages = []
    page = section = None
    for line in SPEC.read_text().splitlines():
        if line.startswith("=== "):
            title, slug, group = [part.strip() for part in line[4:].split("|")]
            page = {"title": title, "slug": slug, "group": group, "summary": [], "sections": []}
            pages.append(page)
            section = None
        elif line.startswith("--- "):
            section = {"title": line[4:].strip(), "text": [], "code": []}
            page["sections"].append(section)
        elif section is None:
            if page is not None and line.strip():
                page["summary"].append(line.strip())
        elif section["code"] or line.startswith("function "):
            section["code"].append(line)
        elif line.strip():
            section["text"].append(line.strip())
    for page in pages:
        for section in page["sections"]:
            code = "\n".join(section["code"]).rstrip()
            name = re.match(r"function (\w+)\(", code)
            if not name:
                sys.exit(f"{page['title']} / {section['title']}: the example must start with `function Name(): Node`")
            section["code"], section["name"] = code, name.group(1)
    return pages


def literal(text):
    return json.dumps(text, ensure_ascii=False)


def component(name):
    return re.sub(r"\W", "", name) + "Page"


def page_source(page, names):
    code = "\n\n".join(section["code"] for section in page["sections"])
    used = sorted(names & set(re.findall(r"\b([A-Za-z_]\w*)\b", code)) | {"View", "Text", "Node"})
    lines = [
        "// Generated by tools/generate-ui-gallery.py from pages.spec. Do not edit.",
        f"import {{ {', '.join(used)} }} from 'std:ui';",
        "import { Example, PageHeader } from '../example.tsrx';",
        "",
        code,
        "",
        f"export function {component(page['title'])}(): Node {{",
        "  return (",
        '    <View className="flex-col gap-10">',
        f"      <PageHeader summary={literal(' '.join(page['summary']))} slug={literal(page['slug'])} />",
    ]
    for section in page["sections"]:
        lines.append(f"      <Example title={literal(section['title'])} description={literal(' '.join(section['text']))} code={literal(section['code'])}><{section['name']} /></Example>")
    lines += ["    </View>", "  );", "}", ""]
    return "\n".join(lines)


def main_source(pages):
    groups = {}
    for page in pages:
        groups.setdefault(page["group"], []).append(page)
    lines = [
        "// Generated by tools/generate-ui-gallery.py from pages.spec. Do not edit.",
        "import { View, Text, Node, Child, signal, run, location, navigate, registerThemes, useTheme, Route, Sidebar, SidebarGroup, SidebarItem, ScrollArea, Switch, TitleBar } from 'std:ui';",
        "import { Introduction } from './introduction.tsrx';",
        "import gruvbox from './themes/gruvbox.json';",
    ]
    for page in pages:
        lines.append(f"import {{ {component(page['title'])} }} from './pages/{page['title'].replace(' ', '')}.tsrx';")
    lines += [
        "",
        "interface PageProps {",
        "  children?: Child[];",
        "}",
        "",
        "function Page(props: PageProps): Node {",
        "  return (",
        '    <ScrollArea className="grow">',
        '      <View className="flex-col p-8 max-w-[960px]" children={props.children ?? []} />',
        "    </ScrollArea>",
        "  );",
        "}",
        "",
        "function App(): Node {",
        "  const path = location();",
        "  const dark = signal(false);",
        "  return (",
        '    <View className="flex-col size-full">',
        "      <TitleBar>",
        '        <Text className="font-semibold">GPUI Kit for Tsrust</Text>',
        '        <View className="grow" />',
        '        <View className="pr-3">',
        "          <Switch label=\"Dark\" checked={dark.get()} onChange={(on) => { dark.set(on); useTheme(on ? 'Gruvbox Dark Medium' : 'Gruvbox Light Medium'); }} />",
        "        </View>",
        "      </TitleBar>",
        '      <View className="flex-row grow min-h-0">',
        "      <Sidebar>",
        '        <SidebarGroup label="Getting started">',
        "          <SidebarItem label=\"Introduction\" active={path.get() === '/'} onClick={() => { navigate('/'); }} />",
        "        </SidebarGroup>",
    ]
    for group, members in groups.items():
        lines.append(f"        <SidebarGroup label={literal(group)}>")
        for page in members:
            route = f"/{page['slug']}"
            lines.append(f"          <SidebarItem label={literal(page['title'])} active={{path.get() === {literal(route)}}} onClick={{() => {{ navigate({literal(route)}); }}}} />")
        lines.append("        </SidebarGroup>")
    lines += [
        "      </Sidebar>",
        '      <View className="flex-col grow min-w-0">',
        "        <Route path=\"/\" render={() => <Page><Introduction /></Page>} />",
    ]
    # Each route owns its scroll area, so navigation starts at the top of the page.
    for page in pages:
        lines.append(f"        <Route path={literal('/' + page['slug'])} render={{() => <Page><{component(page['title'])} /></Page>}} />")
    lines += [
        "      </View>",
        "      </View>",
        "    </View>",
        "  );",
        "}",
        "",
        "function main() {",
        "  registerThemes(gruvbox);",
        "  useTheme('Gruvbox Light Medium');",
        "  unwrap(run(App(), 'GPUI Kit for Tsrust', {",
        "    width: 1280, height: 860, minWidth: 800, minHeight: 560, titlebar: 'custom'",
        "  }));",
        "}",
        "",
    ]
    return "\n".join(lines)


def formatted(files):
    """Format like the project formatter (TSRUST selects the compiler)."""
    compiler = os.environ.get("TSRUST", str(ROOT / "target/debug/tsrust"))
    with tempfile.TemporaryDirectory() as directory:
        for name, text in files.items():
            path = Path(directory) / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        subprocess.run([compiler, "format", directory], check=True, stdout=subprocess.DEVNULL)
        return {name: (Path(directory) / name).read_text() for name in files}


def main():
    check = "--check" in sys.argv[1:]
    pages = parse()
    names = exports()
    files = {f"src/pages/{page['title'].replace(' ', '')}.tsrx": page_source(page, names) for page in pages}
    files["src/main.tsrx"] = main_source(pages)
    files = formatted(files)
    current = {str(path.relative_to(STARTER)) for path in (STARTER / "src/pages").glob("*.tsrx")}
    stale = [name for name, text in files.items() if not (STARTER / name).exists() or (STARTER / name).read_text() != text]
    removed = sorted(current - set(files))
    if check:
        if stale or removed:
            sys.exit("Generated gallery files are stale: " + ", ".join(stale + removed))
        return
    for name, text in files.items():
        path = STARTER / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    for name in removed:
        (STARTER / name).unlink()
    print(f"Generated {len(pages)} pages, {sum(len(page['sections']) for page in pages)} examples")


if __name__ == "__main__":
    main()
