#!/usr/bin/env python3
"""Generate normalization tables offline from pinned Unicode 16.0.0 data."""
from pathlib import Path
import bisect, hashlib, json
from functools import lru_cache
ROOT = Path(__file__).resolve().parent
sources = {name: hashlib.sha256((ROOT/'data'/name).read_bytes()).hexdigest() for name in ['UnicodeData.txt','DerivedNormalizationProps.txt','NormalizationTest.txt','LICENSE.txt']}
manifest_path = ROOT/'sources.json'
if manifest_path.exists():
    assert json.loads(manifest_path.read_text())['sha256'] == sources, 'Pinned Unicode source drift'
else:
    manifest_path.write_text(json.dumps({'unicodeVersion':'16.0.0','baseUrl':'https://www.unicode.org/Public/16.0.0/ucd/','licenseUrl':'https://www.unicode.org/license.txt','sha256':sources},indent=2)+'\n')
excluded=set()
for line in (ROOT/'data/DerivedNormalizationProps.txt').read_text().splitlines():
    fields=line.split('#',1)[0].strip().split(';')
    if len(fields)<2 or fields[1].strip()!='Full_Composition_Exclusion': continue
    bounds=fields[0].strip().split('..');start=int(bounds[0],16);end=int(bounds[-1],16)
    excluded.update(range(start,end+1))
ccc=[];decomp=[];flat=[];compose=[];assigned=[];range_start=None
for line in (ROOT/'data/UnicodeData.txt').read_text().splitlines():
    fields=line.split(';');cp=int(fields[0],16);klass=int(fields[3]);mapping=fields[5].split()
    if fields[1].endswith(', First>'): range_start=cp
    elif fields[1].endswith(', Last>'):
        assert range_start is not None
        if fields[2]!='Cs': assigned.append((range_start,cp))
        range_start=None
    elif fields[2]!='Cs': assigned.append((cp,cp))
    if klass: ccc.append((cp,klass))
    if not mapping: continue
    compatibility=mapping[0].startswith('<')
    if compatibility: mapping=mapping[1:]
    values=[int(value,16) for value in mapping]
    decomp.append((cp,compatibility,len(flat),len(values)));flat.extend(values)
    if not compatibility and len(values)==2 and cp not in excluded: compose.append(((values[0]<<21)|values[1],cp))
compose.sort()
assert len({key for key,_ in compose})==len(compose)
# Expand pinned decomposition chains once; composition pairs still use raw mappings.
original={cp:(compatibility,tuple(flat[start:start+length])) for cp,compatibility,start,length in decomp}
classes=dict(ccc)
assert (len(ccc),len(decomp),len(compose),len(flat))==(934,5913,961,8739)
@lru_cache(None)
def expand(code,compatibility):
    if 0xAC00<=code<0xAC00+11172:
        syllable=code-0xAC00;tail=syllable%28
        return (0x1100+syllable//588,0x1161+syllable%588//28)+((0x11A7+tail,) if tail else ())
    if code not in original: return (code,)
    compatible,values=original[code]
    if compatible and not compatibility: return (code,)
    return tuple(leaf for value in values for leaf in expand(value,compatibility))
def packed(values):
    assert all(0<=code<=0x10FFFF and not 0xD800<=code<=0xDFFF for code in values)
    return [code|(classes.get(code,0)<<21) for code in values]
decomp=[];flat=[];alternatives=[]
for code,(compatible,_) in original.items():
    values=expand(code,compatible);kind=int(compatible)
    if not compatible and values!=expand(code,True):
        kind=2+len(alternatives);alternatives.append((code,expand(code,True)))
    assert kind<=255 and len(values)<=255
    decomp.append((code,kind,len(flat),len(values)));flat.extend(packed(values))
compatibility=[]
for code,values in alternatives:
    assert len(values)<=255
    compatibility.append((code,len(flat),len(values)));flat.extend(packed(values))
assert len(compatibility)==16 and len(flat)==9221
assert all(classes.get(code,0)==0 for code in range(0x1100,0x1200))
output=['// Generated by tools/unicode-normalization/generate.py; do not edit.', '// Unicode 16.0.0 data, SPDX-License-Identifier: Unicode-3.0.', '// License: tools/unicode-normalization/data/LICENSE.txt.']
output.extend('// '+line for line in (ROOT/'data/LICENSE.txt').read_text().splitlines())
for name,typ,rows in [('TSR_NORMALIZATION_CCC','(u32,u8)',ccc),('TSR_NORMALIZATION_DECOMPOSE','(u32,u8,u32,u8)',decomp),('TSR_NORMALIZATION_COMPOSE','(u64,u32)',compose)]:
    output.append(f'const {name}: &[{typ}] = &[')
    output.extend('('+','.join(str(value).lower() for value in row)+'),' for row in rows);output.append('];')
    if name in ['TSR_NORMALIZATION_CCC','TSR_NORMALIZATION_DECOMPOSE']:
        keys=[row[0] for row in rows]
        assert keys==sorted(set(keys))
        pages=[bisect.bisect_left(keys,page<<8) for page in range((keys[-1]>>8)+2)]
        assert pages[0]==0 and pages[-1]==len(rows) and pages[-1]<65536
        assert all(all(key>>8==page for key in keys[start:end]) for page,(start,end) in enumerate(zip(pages,pages[1:])))
        output.append(f'const {name}_PAGES: &[u16] = &[')
        for i in range(0,len(pages),24): output.append(','.join(map(str,pages[i:i+24]))+',')
        output.append('];')
output.append('// Decomposition kinds: 0 canonical, 1 compatibility-only, 2+ compatibility alternative index.')
output.append('const TSR_NORMALIZATION_COMPATIBILITY: &[(u32,u32,u8)] = &[')
output.extend('('+','.join(map(str,row))+'),' for row in compatibility);output.append('];')
output.append('const TSR_NORMALIZATION_MAPPING: &[u32] = &[')
for i in range(0,len(flat),24): output.append(','.join(str(value) for value in flat[i:i+24])+',')
output.append('];')
path=ROOT.parent.parent/'crates/tsrust-compiler/src/runtime/normalization_tables.rs';path.write_text('\n'.join(output)+'\n')
print(f'{len(ccc)} combining classes, {len(decomp)} decompositions, {len(compose)} compositions, {len(flat)} packed mapping scalars, {len(compatibility)} compatibility alternatives')

merged=[]
for start,end in assigned:
    if merged and start==merged[-1][1]+1: merged[-1][1]=end
    else: merged.append([start,end])
(ROOT/'assigned-ranges.json').write_text(json.dumps(merged,separators=(',',':'))+'\n')
(ROOT/'assigned-ranges.rs').write_text('['+','.join(f'({start}u32,{end}u32)' for start,end in merged)+']\n')
