// Run against a real CLI-generated app's live dev servers, in a separate browser.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const project = path.resolve(process.argv[2] || 'generated-projects/greeting-web');
const url = process.env.APPLICATION_WEB_URL || 'http://127.0.0.1:5173';
const { chromium } = await import(pathToFileURL(path.join(repository, 'examples/backend-tasks/web/node_modules/@playwright/test/index.mjs')));
const { default: AxeBuilder } = await import(pathToFileURL(path.join(repository, 'examples/backend-tasks/web/node_modules/@axe-core/playwright/dist/index.mjs')));
const source = path.join(project, 'web/src/App.tsx');
const original = fs.readFileSync(source, 'utf8');
const receiptFile = fs.existsSync(path.join(project, 'generated/.tsrust-integration.json')) ? 'generated/.tsrust-integration.json' : 'tsrust.integration.json';
const receipt = JSON.parse(fs.readFileSync(path.join(project, receiptFile), 'utf8'));
assert.equal(createHash('sha256').update(original).digest('hex'), receipt.initialFiles['web/src/App.tsx'], 'Use a fresh CLI project for source-edit acceptance; preserve owner customizations');
const typesFile = path.join(project, 'web/src/api-contract-check.ts');
const typesSource = `// Compile-only witness; never imported by the application.\nimport { api } from './lib/api'\napi.greet('Ada')\n// @ts-expect-error the native parameter is a string, not an object\napi.greet({ name: 'Ada' })\n// @ts-expect-error numbers are rejected\napi.greet(42)\n// @ts-expect-error undeclared operations are unavailable\napi.missing()\n`;
let edited, ownsTypes = false;
const browser = await chromium.launch({ headless: true });
try {
  fs.writeFileSync(typesFile, typesSource, { flag: 'wx' });
  ownsTypes = true;
  const pnpm = process.env.PNPM || (process.platform === 'win32' ? path.join(process.env.APPDATA, 'npm/node_modules/pnpm/pnpm.exe') : 'pnpm');
  const types = spawnSync(pnpm, ['exec', 'tsc', '--noEmit'], { cwd: path.join(project, 'web'), encoding: 'utf8', windowsHide: true, timeout: 30000 });
  assert.ifError(types.error); assert.equal(types.status, 0, types.stdout + types.stderr);
  assert.equal(fs.readFileSync(typesFile, 'utf8'), typesSource); fs.unlinkSync(typesFile); ownsTypes = false;
  const context = await browser.newContext();
  const page = await context.newPage(); const exceptions = [], rejectedAssets = [];
  page.on('pageerror', error => exceptions.push(error.message));
  page.on('response', response => { if (response.status() >= 400 && response.url().startsWith(url) && new URL(response.url()).pathname !== '/api') rejectedAssets.push(response.url()); });
  await page.goto(url);
  await page.getByRole('heading', { name: 'Your app starts here.', exact: true }).waitFor();
  assert.equal(await page.evaluate(async () => { await document.fonts.ready; return [...document.fonts].some(font => font.family.includes('Geist') && font.status === 'loaded'); }), true, 'The actual workspace font must load');
  assert.deepEqual(rejectedAssets, [], 'Development assets must not be rejected by the filesystem allowlist');
  await page.getByLabel('Your name', { exact: true }).fill('Ada');
  await page.getByRole('button', { name: 'Greet server', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /^Hello, Ada!$/ }).waitFor();
  await page.getByLabel('Your name', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Greet server', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /^Hello, world!$/ }).waitFor();
  assert.deepEqual((await new AxeBuilder({ page }).analyze()).violations, []);
  let release;
  const held = new Promise(resolve => { release = resolve; });
  await page.route('**/api', async route => { await held; await route.continue(); });
  await page.getByRole('button', { name: 'Greet server', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Waiting for the server…' }).waitFor(); release();
  await page.getByRole('status').filter({ hasText: /^Hello, world!$/ }).waitFor();
  await page.unroute('**/api');
  await page.route('**/api', route => route.abort());
  await page.getByRole('button', { name: 'Greet server', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Could not reach the server.' }).waitFor();
  await page.unroute('**/api');
  await page.getByRole('button', { name: 'Greet server', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /^Hello, world!$/ }).waitFor();
  await page.evaluate(() => { globalThis.applicationHmrWitness = 'same-document'; });
  edited = original.replace('Your app starts here.', 'Your editable application.'); assert.notEqual(edited, original);
  assert.equal(fs.readFileSync(source, 'utf8'), original, 'Source changed during acceptance');
  fs.writeFileSync(source, edited);
  await page.getByRole('heading', { name: 'Your editable application.', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => globalThis.applicationHmrWitness), 'same-document');
  assert.equal(fs.readFileSync(source, 'utf8'), edited, 'Preserve concurrent owner edits');
  fs.writeFileSync(source, original); edited = undefined;
  await page.getByRole('heading', { name: 'Your app starts here.', exact: true }).waitFor();
  await page.setViewportSize({ width: 375, height: 812 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(repository, 'target/application-web.png'), fullPage: true });
  assert.deepEqual(exceptions, []);
  console.log('CLI-generated web app: typed valid/invalid SDK calls, actual native greeting/empty input, loading, failed call/recovery, axe accessibility, mobile layout and source HMR without document replacement passed.');
} finally {
  if (edited && fs.readFileSync(source, 'utf8') === edited) fs.writeFileSync(source, original);
  if (ownsTypes && fs.existsSync(typesFile) && fs.readFileSync(typesFile, 'utf8') === typesSource) fs.unlinkSync(typesFile);
  await browser.close();
}
