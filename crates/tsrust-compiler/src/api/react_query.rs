//! Optional React/TanStack declarations reference the plain client's checked calls.
use super::{Kind, Manifest};
use std::collections::BTreeMap;

#[derive(Default)]
struct Namespace<'a> { children: BTreeMap<&'a str, Namespace<'a>>, operation: Option<&'a super::Operation> }
impl<'a> Namespace<'a> {
    fn declaration(&self, path: &str) -> String {
        format!("{{\n{}\n}}", self.children.iter().map(|(name, node)| {
            let access = format!("{path}[{}]", serde_json::to_string(name).unwrap());
            let declaration = if let Some(operation) = node.operation {
                format!("{}<{access}, {}>", if operation.kind == Kind::Query { "QueryOperation" } else { "MutationOperation" }, serde_json::to_string(&operation.name).unwrap())
            } else { node.declaration(&access) };
            format!("readonly {}: {declaration};", serde_json::to_string(name).unwrap())
        }).collect::<Vec<_>>().join("\n"))
    }
}

pub(super) fn declarations(manifest: &Manifest) -> String {
    let mut namespace = Namespace::default();
    for operation in &manifest.operations {
        let mut node = &mut namespace;
        for segment in operation.name.split('.') { node = node.children.entry(segment).or_default(); }
        node.operation = Some(operation);
    }
    format!(r#"// @generated by tsrust api. Only this optional entry needs React/TanStack.
import {{ queryOptions, skipToken, type QueryClient, type UseQueryOptions, type UseQueryResult, type UseMutationOptions, type UseMutationResult }} from '@tanstack/react-query';
import type {{ Client, Transport, CallOptions, ApiError }} from './index.js';
type Call = (input: any, options?: CallOptions) => Promise<any>;
type Input<F extends Call> = Parameters<F>[0];
type Output<F extends Call> = Awaited<ReturnType<F>>;
export type ApiQueryKey<N extends string = string> = readonly ['tsrust', string, string, N, string];
type QuerySettings<F extends Call, Selected, N extends string> = Omit<UseQueryOptions<Output<F>, ApiError, Selected, ApiQueryKey<N>>, 'queryKey' | 'queryFn' | 'queryHash' | 'queryKeyHashFn'>;
type QueryArguments<F extends Call, Selected, N extends string> = undefined extends Input<F> ? [input?: Input<F> | typeof skipToken, options?: QuerySettings<F, Selected, N>] : [input: Input<F> | typeof skipToken, options?: QuerySettings<F, Selected, N>];
type QueryOperation<F extends Call, N extends string> = F & {{
  key(...input: undefined extends Input<F> ? [input?: Input<F>] : [input: Input<F>]): ApiQueryKey<N>;
  queryOptions<Selected = Output<F>>(...args: QueryArguments<F, Selected, N>): ReturnType<typeof queryOptions<Output<F>, ApiError, Selected, ApiQueryKey<N>>>;
  useQuery<Selected = Output<F>>(...args: [...QueryArguments<F, Selected, N>, queryClient?: QueryClient]): UseQueryResult<Selected, ApiError>;
}};
type MutationSettings<F extends Call, Context> = Omit<UseMutationOptions<Output<F>, ApiError, Input<F>, Context>, 'mutationKey' | 'mutationFn'>;
type MutationOperation<F extends Call, N extends string> = F & {{
  mutationOptions<Context = unknown>(options?: MutationSettings<F, Context>): UseMutationOptions<Output<F>, ApiError, Input<F>, Context> & {{ mutationKey: readonly ['tsrust', string, string, N] }};
  useMutation<Context = unknown>(options?: MutationSettings<F, Context>, queryClient?: QueryClient): UseMutationResult<Output<F>, ApiError, Input<F>, Context>;
}};
export type ReactClient = {};
export interface ReactClientOptions {{ readonly scope: string; }}
export declare function createReactClient(transport: Transport, options: ReactClientOptions): ReactClient;
"#, namespace.declaration("Client"))
}

pub(super) fn core_declarations(manifest: &Manifest) -> String {
    let mut namespace = Namespace::default();
    for operation in &manifest.operations {
        let mut node = &mut namespace;
        for segment in operation.name.split('.') { node = node.children.entry(segment).or_default(); }
        node.operation = Some(operation);
    }
    format!(r#"// @generated by tsrust api. Framework-independent TanStack options.
import {{ skipToken, type DataTag, type QueryObserverOptions, type MutationObserverOptions }} from '@tanstack/query-core';
import type {{ Client, Transport, CallOptions, ApiError }} from './index.js';
type Call = (input: any, options?: CallOptions) => Promise<any>;
type Input<F extends Call> = Parameters<F>[0];
type Output<F extends Call> = Awaited<ReturnType<F>>;
export type ApiQueryKey<N extends string = string> = readonly ['tsrust', string, string, N, string];
type QuerySettings<F extends Call, Selected, N extends string> = Omit<QueryObserverOptions<Output<F>, ApiError, Selected, Output<F>, ApiQueryKey<N>>, 'queryKey' | 'queryFn' | 'queryHash' | 'queryKeyHashFn'>;
type QueryArguments<F extends Call, Selected, N extends string> = undefined extends Input<F> ? [input?: Input<F> | typeof skipToken, options?: QuerySettings<F, Selected, N>] : [input: Input<F> | typeof skipToken, options?: QuerySettings<F, Selected, N>];
type QueryOperation<F extends Call, N extends string> = F & {{
  key(...input: undefined extends Input<F> ? [input?: Input<F>] : [input: Input<F>]): ApiQueryKey<N>;
  queryOptions<Selected = Output<F>>(...args: QueryArguments<F, Selected, N>): QueryObserverOptions<Output<F>, ApiError, Selected, Output<F>, ApiQueryKey<N>> & {{ queryKey: DataTag<ApiQueryKey<N>, Output<F>, ApiError> }};
}};
type MutationSettings<F extends Call, Context> = Omit<MutationObserverOptions<Output<F>, ApiError, Input<F>, Context>, 'mutationKey' | 'mutationFn'>;
type MutationOperation<F extends Call, N extends string> = F & {{
  mutationOptions<Context = unknown>(options?: MutationSettings<F, Context>): MutationObserverOptions<Output<F>, ApiError, Input<F>, Context> & {{ mutationKey: readonly ['tsrust', string, string, N] }};
}};
export type QueryClient = {};
export interface QueryClientOptions {{ readonly scope: string; }}
export declare function createQueryClient(transport: Transport, options: QueryClientOptions): QueryClient;
"#, namespace.declaration("Client"))
}
