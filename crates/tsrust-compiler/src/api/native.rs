//! A private checked source adapter; application state never enters the package.
use super::{ApiHistory, CheckedApi, Manifest, Schema, native_codecs::Codecs};
use std::{collections::BTreeMap, path::Path};

pub struct NativeImport { pub module: String, pub export: String }
pub struct NativeServer {
    pub context: NativeImport,
    pub authorize: NativeImport,
    pub previous: Vec<Manifest>,
    pub max_request_bytes: u32,
    pub max_response_bytes: u32,
}

fn text(value: &str) -> String { serde_json::to_string(value).expect("source string") }
fn identifier(value: &str) -> bool {
    let mut chars = value.chars();
    chars.next().is_some_and(|character| character.is_alphabetic() || matches!(character, '_' | '$'))
        && chars.all(|character| character.is_alphanumeric() || matches!(character, '_' | '$'))
}
fn import(source: &NativeImport, alias: &str, parent: &Path) -> Result<String, String> {
    if !identifier(&source.export) { return Err("Native API imports require named source exports".into()); }
    let target = Path::new(&source.module).components().collect::<Vec<_>>();
    let base = parent.components().collect::<Vec<_>>();
    let common = base.iter().zip(&target).take_while(|(base, target)| base == target).count();
    if common == 0 { return Err("Native API source and backend modules must share a filesystem volume".into()); }
    let mut parts = vec!["..".to_owned(); base.len() - common];
    parts.extend(target[common..].iter().map(|part| part.as_os_str().to_str().map(str::to_owned).ok_or("Native API import paths must be UTF-8")).collect::<Result<Vec<_>, _>>()?);
    let relative = parts.join("/");
    let relative = if relative.starts_with("../") { relative } else { format!("./{relative}") };
    Ok(format!("import {{{} as {alias}}} from {};\n", source.export, text(&relative)))
}

impl CheckedApi {
    /// Return private source for virtual checking before any generated file is
    /// replaced. Paths are canonical module identities; output is a virtual file.
    pub fn native_source(&self, output: &Path, options: &NativeServer) -> Result<String, String> {
        self.native_source_impl(output, options, None)
    }

    pub fn native_source_versioned(&self, output: &Path, options: &NativeServer, history: &ApiHistory) -> Result<String, String> {
        history.validate()?;
        let release = history.releases.iter().rev().find(|release| release.sdk_version.is_some()).ok_or("API history needs a current release")?;
        if release.manifest != self.manifest { return Err("Native API history does not describe the checked operations".into()); }
        self.native_source_impl(output, options, Some(history))
    }

    fn native_source_impl(&self, output: &Path, options: &NativeServer, history: Option<&ApiHistory>) -> Result<String, String> {
        let parent = output.parent().ok_or("Native API output needs a parent directory")?;
        for limit in [options.max_request_bytes, options.max_response_bytes] {
            if !(1..=16_777_216).contains(&limit) { return Err("API byte limits must be from 1 to 16777216".into()); }
        }
        let api_version = history.and_then(|history| history.releases.iter().rev().find(|release| release.sdk_version.is_some())).map_or(1, |release| release.api_version);
        let current = self.manifest.wire_identity(api_version);
        let mut previous = BTreeMap::new();
        for manifest in &options.previous {
            manifest.validate()?;
            let identity = manifest.identity();
            if identity != current { previous.insert(identity, (1, manifest)); }
        }
        if let Some(history) = history {
            for release in &history.releases {
                let identity = release.manifest.wire_identity(release.api_version);
                if identity != current { previous.insert(identity, (release.api_version, &release.manifest)); }
            }
        }
        let mut source = "// @generated by tsrust api. Private native dispatch; do not publish.\nimport {Response} from 'std:http';\nimport {JsonRaw} from 'std:json';\nimport {s} from 'std:schema';\n".to_owned();
        source.push_str(&import(&options.context, "_ApiContext", parent)?);
        source.push_str(&import(&options.authorize, "_authorize", parent)?);
        let mut codecs = Codecs::default();
        let mut dispatch = String::new();
        for (index, operation) in self.manifest.operations.iter().enumerate() {
            let endpoint = &self.endpoints[&operation.name];
            source.push_str(&import(&NativeImport { module: endpoint.selection.module.clone(), export: endpoint.selection.export.clone() }, &format!("_operation{index}"), parent)?);
            let name = text(&operation.name);
            let input = codecs.define(&operation.input, false);
            let output = codecs.define(&operation.output, false);
            let compatible = previous.iter().filter_map(|(identity, (version, manifest))| {
                manifest.operations.iter().find(|old| operation.supports_previous(old)).map(|old| (identity, *version, old))
            }).collect::<Vec<_>>();
            let current_operation = operation.wire_identity(api_version);
            let accepted_profile = |identity: &str, version: u32, operation: &super::Operation| format!("((requestedApiVersion===undefined||requestedApiVersion==={version:?})&&(contract==={}||(requestedApiVersion==={version:?}&&operationContract==={})))", text(identity), text(&operation.wire_identity(version)), version=version.to_string());
            let accepted = std::iter::once(accepted_profile(&current, api_version, operation))
                .chain(compatible.iter().map(|(identity, version, old)| accepted_profile(identity, *version, old))).collect::<Vec<_>>().join("||");
            dispatch.push_str(&format!("if(header.operation==={name}){{\nif(!({accepted})){{return _failure(c,'api-incompatible','This operation is incompatible with the calling API client',409);}}\nconst decoded=s.object({{operation:s.literal({name}),input:{}()}}).safeParseJson(body);\nif(!decoded.success){{return _failure(c,'api-validation','Invalid operation arguments',400);}}\ntry{{\n", input.schema));
            let mut arguments = Vec::new();
            if endpoint.selection.context { arguments.push("c".into()); }
            if operation.input != Schema::Void {
                dispatch.push_str("const input=decoded;\n");
                arguments.push(format!("{}(input.data.input)", input.adapt));
            }
            let call = format!("{}{}_operation{index}({});", if operation.output == Schema::Void { "" } else { "const result=" }, if endpoint.asynchronous { "await " } else { "" }, arguments.join(","));
            dispatch.push_str(&call);
            dispatch.push_str(&format!("\nconst encoded=JSON.stringify({},{});\nconst checked={}().safeParseJson(encoded);\nif(!checked.success){{return _failure(c,'api-result','Operation returned invalid API data',500);}}\n", if operation.output == Schema::Void { "null" } else { "result" }, options.max_response_bytes, output.schema));
            dispatch.push_str(&format!("if(requestedApiVersion==={}&&operationContract==={}){{return _success(c,checked.data);}}\n", text(&api_version.to_string()), text(&current_operation)));
            for (identity, version, old) in compatible {
                let codec = codecs.define(&old.output, true);
                dispatch.push_str(&format!("if((requestedApiVersion==={}&&operationContract==={})||contract==={}){{const projected={}().safeParseJson(encoded);if(!projected.success){{return _failure(c,'api-result','Operation returned incompatible API data',500);}}return _success(c,projected.data);}}\n", text(&version.to_string()), text(&old.wire_identity(version)), text(identity), codec.schema));
            }
            dispatch.push_str("return _success(c,checked.data);\n}catch{return _failure(c,'api-internal','Operation failed; completion may be unknown',500);}\n}\n");
        }
        source.push_str(&codecs.source);
        source.push_str(&format!(r#"
type _Header={{operation:string;input:JsonRaw;}};
type _PublicError={{code:string;message:string;}};
type _FailureEnvelope={{ok:false;error:_PublicError;}};
type _SuccessEnvelope<T>={{ok:true;value:T;}};
function _send(c:Mutable<_ApiContext>,body:string,status:int):Response{{
  c.header('content-type','application/json');c.header('cache-control','no-store');
  c.header('x-content-type-options','nosniff');c.header('x-tsrust-contract',{});
  return c.text(body,status);
}}
function _failure(c:Mutable<_ApiContext>,code:string,message:string,status:int):Response{{
  const envelope:_FailureEnvelope={{ok:false,error:{{code,message}}}};
  return _send(c,JSON.stringify(envelope),status);
}}
function _success<T>(c:Mutable<_ApiContext>,value:T):Response{{
  const envelope:_SuccessEnvelope<T>={{ok:true,value}};
  return _send(c,JSON.stringify(envelope,{}),200);
}}
function _parameter(contentType:string,name:string):string|undefined{{
  let found:string|undefined=undefined;
  for(const part of contentType.split(';')){{
    const item=part.trim();
    if(item.toLowerCase().startsWith(name+'=')){{
      if(found!==undefined){{throw 'Duplicate API media parameter';}}
      found=item.slice(name.length+1);
    }}
  }}
  return found;
}}
async function _invoke(c:Mutable<_ApiContext>,body:string):Task<Response>{{
  const header=JSON.parse<_Header>(body);
  const contract=c.req.header('x-tsrust-contract');
  const contentType=c.req.header('content-type');
  if(contentType===undefined){{return _failure(c,'api-media-type','API requests require application/json',415);}}
  const requestedApiVersion=_parameter(contentType,'tsrust-api');
  const operationContract=_parameter(contentType,'tsrust-operation');
  if(operationContract!==undefined&&requestedApiVersion===undefined){{return _failure(c,'api-protocol','Operation metadata requires an API version',400);}}
  {dispatch}
  return _failure(c,'api-operation','Operation is not declared',404);
}}
export async function dispatch(c:Mutable<_ApiContext>):Task<Response>{{
  try{{const allowed=await _authorize(c);if(!allowed){{return _failure(c,'api-denied','Access denied',403);}}}}
  catch{{return _failure(c,'api-internal','Application access policy failed',500);}}
  if(c.req.method()!=='POST'){{return _failure(c,'api-method','API requests require POST',405);}}
  const contentType=c.req.header('content-type');
  if(contentType===undefined){{return _failure(c,'api-media-type','API requests require application/json',415);}}
  if(contentType.split(';')[0].trim().toLowerCase()!=='application/json'){{return _failure(c,'api-media-type','API requests require application/json',415);}}
  try{{
    const body=await c.req.text();
    if(body.length>{}){{return _failure(c,'api-request-limit','API request is too large',413);}}
    return await _invoke(c,body);
  }}catch{{return _failure(c,'api-validation','Invalid API request',400);}}
}}
"#, text(&current), options.max_response_bytes, options.max_request_bytes));
        if let Some(history) = history {
            let description = super::HttpDescription::new(history.clone())?;
            for (name, body) in [
                ("describe", serde_json::to_string(&description)),
                ("openapi", serde_json::to_string(&description.openapi()?)),
            ] {
                let body = body.map_err(|error| error.to_string())?;
                if body.len() > 1_048_576 { return Err("Public HTTP description exceeds 1 MiB".into()); }
                // Metadata is opt-in at the application router and shares the
                // application's authorization policy; generation never exposes it.
                source.push_str(&format!(r#"
export async function {name}(c:Mutable<_ApiContext>):Task<Response>{{
  try{{const allowed=await _authorize(c);if(!allowed){{return _failure(c,'api-denied','Access denied',403);}}}}
  catch{{return _failure(c,'api-internal','Application access policy failed',500);}}
  if(c.req.method()!=='GET'){{return _failure(c,'api-method','API descriptions require GET',405);}}
  return _send(c,{},200);
}}
"#, text(&body)));
            }
        }
        Ok(source)
    }
}
