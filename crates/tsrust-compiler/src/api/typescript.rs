use super::{Manifest, Schema};
use std::collections::BTreeMap;

fn text(value: &str) -> String { serde_json::to_string(value).expect("JSON string") }

fn ty(schema: &Schema) -> String {
    match schema {
        Schema::String => "string".into(),
        Schema::Integer | Schema::Number => "number".into(),
        Schema::Boolean => "boolean".into(),
        Schema::Null => "null".into(),
        Schema::Void => "void".into(),
        Schema::Literal { value } => value.to_string(),
        Schema::Array { items } => format!("({})[]", ty(items)),
        Schema::Tuple { items } => format!("[{}]", items.iter().map(ty).collect::<Vec<_>>().join(", ")),
        Schema::Union { members } => format!("({})", members.iter().map(ty).collect::<Vec<_>>().join(" | ")),
        Schema::Object { properties, required } => format!("{{ {} }}", properties.iter().map(|(name, schema)|
            format!("{}{}: {};", text(name), if required.contains(name) { "" } else { "?" }, ty(schema))).collect::<Vec<_>>().join(" ")),
    }
}

#[derive(Default)]
struct Namespace<'a> { children: BTreeMap<&'a str, Namespace<'a>>, operation: Option<&'a super::Operation> }
impl<'a> Namespace<'a> {
    fn declaration(&self) -> String {
        format!("{{\n{}\n}}", self.children.iter().map(|(name, node)| {
            let declaration = if let Some(operation) = node.operation {
                format!("(input{}: {}, options?: CallOptions) => Promise<{}>", if operation.input == Schema::Void { "?" } else { "" }, ty(&operation.input), ty(&operation.output))
            } else { node.declaration() };
            format!("readonly {}: {declaration};", text(name))
        }).collect::<Vec<_>>().join("\n"))
    }
}

pub(super) fn package(manifest: &Manifest, name: &str, version: &str) -> Result<BTreeMap<String, String>, String> {
    let valid_part = |part: &str| !part.is_empty() && part.as_bytes()[0].is_ascii_alphanumeric()
        && part.bytes().all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || matches!(byte, b'-' | b'_' | b'.'));
    let valid_name = if let Some(scoped) = name.strip_prefix('@') {
        scoped.split_once('/').is_some_and(|(scope, name)| valid_part(scope) && valid_part(name))
    } else { valid_part(name) };
    if !valid_name || name.len() > 214 { return Err("API package name must be a lowercase npm name, optionally @scope/name".into()); }
    let parts = version.split('.').collect::<Vec<_>>();
    if parts.len() != 3 || parts.iter().any(|part| part.is_empty() || part.len() > 1 && part.starts_with('0') || !part.bytes().all(|byte| byte.is_ascii_digit()) || part.parse::<u32>().is_err()) {
        return Err("Initial API package version must be major.minor.patch with nonnegative integers".into());
    }
    if manifest.schema_version != 1 { return Err("Unsupported API manifest version".into()); }
    let mut namespace = Namespace::default();
    for operation in &manifest.operations {
        let mut node = &mut namespace;
        for segment in operation.name.split('.') { node = node.children.entry(segment).or_default(); }
        node.operation = Some(operation);
    }
    let declarations = format!(r#"// @generated by tsrust api.
export interface CallOptions {{ readonly signal?: {{ readonly aborted: boolean; readonly reason?: unknown; addEventListener(type: 'abort', listener: () => void, options?: {{ once?: boolean }}): void; removeEventListener(type: 'abort', listener: () => void): void; }}; }}
export interface Transport {{ request(operation: string, input: unknown, options?: CallOptions): Promise<unknown>; }}
export declare class ApiError extends Error {{ readonly code: string; readonly operation: string; constructor(code: string, message: string, operation: string); }}
export declare const contractId: string;
export declare const manifest: Readonly<{{ schemaVersion: 1; operations: readonly Readonly<{{ name: string; kind: 'query' | 'mutation'; input: unknown; output: unknown; }}>[]; }}>;
export type Client = {};
export declare function createClient(transport: Transport): Client;
"#, namespace.declaration());
    let javascript = include_str!("client.js")
        .replace("__TSRUST_API_ID__", &text(&manifest.identity()))
        .replace("__TSRUST_API_MANIFEST__", &text(&serde_json::to_string(manifest).map_err(|error| error.to_string())?));
    let package = serde_json::json!({
        "name": name, "version": version, "private": true, "type": "module", "sideEffects": false,
        "exports": {".": {"types": "./index.d.ts", "import": "./index.js"}},
        "files": ["index.js", "index.d.ts", "manifest.json", "README.md", "TSRUST-LICENSE"],
    });
    Ok(BTreeMap::from([
        ("index.js".into(), javascript),
        ("index.d.ts".into(), declarations),
        ("manifest.json".into(), format!("{}\n", serde_json::to_string_pretty(manifest).map_err(|error| error.to_string())?)),
        ("package.json".into(), format!("{}\n", serde_json::to_string_pretty(&package).map_err(|error| error.to_string())?)),
        ("TSRUST-LICENSE".into(), include_str!("../../../../LICENSE").into()),
        ("README.md".into(), "# Generated Tsrust API client\n\nImport createClient and supply a transport. Named calls validate inputs and results.\nWire integers must be safe JavaScript integers; numbers must be finite. Optional\nfields omit undefined; null remains distinct. Unknown fields, resources and\nrecursive data reject. Void results use a null wire value and return undefined.\nThe transport returns {ok:true,value} or {ok:false,error:{code,message}}.\nCalls do not add caching or retries. This ordinary ESM package has no framework\ndependencies, install scripts or backend source. It is private by default; review\nits contents and metadata before explicitly enabling publication.\n".into()),
    ]))
}
