//! Partition generated application functions into child modules for native builds.
//!
//! rustc forms incremental codegen units from source modules. Generated programs
//! put every function in the crate root, so a one-line edit re-ran LLVM over the
//! whole application. Moving the generated function bodies into a few dozen child
//! modules lets rustc reuse the unchanged units: a one-line edit in the GPUI starter
//! went from 17s to 7s of rustc time, and cold builds parallelize better.
//!
//! Only `functionN` and `tsr_result_functionN` items move. Child modules see private
//! crate-root items through `use super::*`, and the root sees the moved functions
//! through a glob import of each `pub(super)` function. Boundaries come from a small
//! lexer that tracks delimiters, strings, raw strings, characters and comments, so a
//! split never lands inside a literal. `tsrust emit` output is left unchanged.

/// Approximate generated bytes per child module; rustc reuse was flat from 60 to 300 KB.
pub const DEFAULT_UNIT_BYTES: usize = 150_000;

pub fn partition(application: &str) -> String {
    partition_with(application, DEFAULT_UNIT_BYTES)
}

pub fn partition_with(application: &str, unit_bytes: usize) -> String {
    let Some(items) = top_level_items(application) else {
        return application.to_owned();
    };
    let mut output = String::with_capacity(application.len() + application.len() / 64);
    let mut unit = String::new();
    let mut units = 0usize;
    let flush = |unit: &mut String, output: &mut String, units: &mut usize| {
        if unit.is_empty() {
            return;
        }
        output.push_str(&format!("mod tsrust_generated_unit{units} {{ use super::*;\n"));
        output.push_str(unit);
        if !unit.ends_with('\n') {
            output.push('\n');
        }
        output.push_str(&format!("}}\nuse tsrust_generated_unit{units}::*;\n"));
        *units += 1;
        unit.clear();
    };
    let mut moving = true;
    for item in items {
        let text = &application[item.start..item.end];
        let head = &application[item.head..item.end];
        // Modules and later items may rely on textual macro order; stop at the first module.
        if module_head(head) {
            moving = false;
        }
        if moving && let Some(offset) = generated_function(head) {
            let insert = item.head - item.start + offset;
            unit.push_str(&text[..insert]);
            unit.push_str("pub(super) ");
            unit.push_str(&text[insert..]);
            if unit.len() >= unit_bytes {
                flush(&mut unit, &mut output, &mut units);
            }
        } else {
            output.push_str(text);
        }
    }
    flush(&mut unit, &mut output, &mut units);
    output
}

struct Item {
    /// Start including leading attributes.
    start: usize,
    /// Start of the item keyword line.
    head: usize,
    end: usize,
}

fn module_head(head: &str) -> bool {
    let head = head.strip_prefix("pub ").unwrap_or(head);
    head.starts_with("mod ")
}

/// Byte offset of `fn`/`async fn` in a movable generated function head.
fn generated_function(head: &str) -> Option<usize> {
    let (offset, rest) = match head.strip_prefix("async ") {
        Some(rest) => (0, rest),
        None => (0, head),
    };
    let name = rest.strip_prefix("fn ")?;
    let digits = name
        .strip_prefix("tsr_result_function")
        .or_else(|| name.strip_prefix("function"))?;
    let count = digits.bytes().take_while(u8::is_ascii_digit).count();
    (count > 0 && matches!(digits.as_bytes().get(count), Some(b'(' | b'<'))).then_some(offset)
}

/// Split the source at top-level line starts, or `None` if delimiters do not balance.
fn top_level_items(source: &str) -> Option<Vec<Item>> {
    let starts = top_level_line_starts(source)?;
    let mut items = Vec::new();
    let mut pending_attributes: Option<usize> = None;
    let mut previous: Option<(usize, usize)> = None;
    let close = |items: &mut Vec<Item>, previous: Option<(usize, usize)>, end: usize| {
        if let Some((start, head)) = previous {
            items.push(Item { start, head, end });
        }
    };
    for start in starts {
        let line = &source[start..];
        if line.starts_with("#[") && !line.starts_with("#![") {
            // An attribute line belongs to the next item.
            if let Some(end) = line.find('\n')
                && !line[..end].trim_end().ends_with(']')
            {
                // Multi-line attribute: treat as ordinary text.
            } else {
                close(&mut items, previous.take(), start);
                pending_attributes.get_or_insert(start);
                continue;
            }
        }
        if item_keyword(line) || previous.is_none() {
            close(&mut items, previous.take(), pending_attributes.unwrap_or(start));
            previous = Some((pending_attributes.take().unwrap_or(start), start));
        } else if let Some(attributes) = pending_attributes.take() {
            // Attributes followed by a non-item line stay as plain text.
            previous = Some((attributes, start));
        }
    }
    let end = source.len();
    if let Some(attributes) = pending_attributes {
        close(&mut items, previous.take(), attributes);
        items.push(Item { start: attributes, head: attributes, end });
    } else {
        close(&mut items, previous, end);
    }
    if items.first().is_some_and(|item| item.start != 0) {
        items.insert(0, Item { start: 0, head: 0, end: items[0].start });
    }
    Some(items)
}

fn item_keyword(line: &str) -> bool {
    let mut line = line;
    for prefix in ["pub(crate) ", "pub(super) ", "pub "] {
        if let Some(rest) = line.strip_prefix(prefix) {
            line = rest;
            break;
        }
    }
    for prefix in ["async ", "unsafe ", "extern "] {
        if let Some(rest) = line.strip_prefix(prefix) {
            line = rest;
        }
    }
    ["fn ", "struct ", "enum ", "impl", "const ", "static ", "type ", "trait ", "use ", "mod ", "union ", "macro_rules!"]
        .iter()
        .any(|keyword| line.starts_with(keyword))
}

/// Offsets of lines that begin outside every delimiter, literal and comment.
fn top_level_line_starts(source: &str) -> Option<Vec<usize>> {
    let bytes = source.as_bytes();
    let mut starts = vec![0];
    let mut depth = 0i64;
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'\n' => {
                if depth == 0 && index + 1 < bytes.len() {
                    starts.push(index + 1);
                }
                index += 1;
            }
            b'{' | b'(' | b'[' => {
                depth += 1;
                index += 1;
            }
            b'}' | b')' | b']' => {
                depth -= 1;
                if depth < 0 {
                    return None;
                }
                index += 1;
            }
            b'/' if bytes.get(index + 1) == Some(&b'/') => {
                index = source[index..].find('\n').map_or(bytes.len(), |end| index + end);
            }
            b'/' if bytes.get(index + 1) == Some(&b'*') => {
                let mut nesting = 1;
                index += 2;
                while nesting > 0 {
                    match (bytes.get(index), bytes.get(index + 1)) {
                        (Some(b'/'), Some(b'*')) => {
                            nesting += 1;
                            index += 2;
                        }
                        (Some(b'*'), Some(b'/')) => {
                            nesting -= 1;
                            index += 2;
                        }
                        (Some(_), _) => index += 1,
                        (None, _) => return None,
                    }
                }
            }
            b'"' => index = skip_string(bytes, index + 1)?,
            b'r' | b'b' | b'c' if !identifier_byte(previous(bytes, index)) => {
                index = skip_prefixed_literal(bytes, index).unwrap_or(index + 1);
            }
            b'\'' => index = skip_quote(source, index)?,
            _ => index += 1,
        }
    }
    (depth == 0).then_some(starts)
}

fn previous(bytes: &[u8], index: usize) -> u8 {
    if index == 0 { b' ' } else { bytes[index - 1] }
}

fn identifier_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_' || byte >= 0x80
}

/// Index after a closing quote; escapes skip one byte.
fn skip_string(bytes: &[u8], mut index: usize) -> Option<usize> {
    while index < bytes.len() {
        match bytes[index] {
            b'\\' => index += 2,
            b'"' => return Some(index + 1),
            _ => index += 1,
        }
    }
    None
}

/// `b"…"`, `c"…"`, `r#"…"#`, `br#"…"#`, `b'…'`; `None` when this is an identifier.
fn skip_prefixed_literal(bytes: &[u8], start: usize) -> Option<usize> {
    let mut index = start;
    if matches!(bytes[index], b'b' | b'c') {
        index += 1;
        match bytes.get(index) {
            Some(b'"') => return skip_string(bytes, index + 1),
            Some(b'\'') if bytes[start] == b'b' => {
                let mut end = index + 1;
                if bytes.get(end) == Some(&b'\\') {
                    end += 1;
                }
                end += 1;
                while bytes.get(end).is_some_and(|byte| *byte != b'\'') {
                    end += 1;
                }
                return (end < bytes.len()).then_some(end + 1);
            }
            Some(b'r') => {}
            _ => return None,
        }
    }
    if bytes.get(index) != Some(&b'r') {
        return None;
    }
    index += 1;
    let hashes = bytes[index..].iter().take_while(|byte| **byte == b'#').count();
    index += hashes;
    if bytes.get(index) != Some(&b'"') {
        return None;
    }
    index += 1;
    loop {
        let quote = index + bytes.get(index..)?.iter().position(|byte| *byte == b'"')?;
        if bytes.get(quote + 1..quote + 1 + hashes)?.iter().all(|byte| *byte == b'#') {
            return Some(quote + 1 + hashes);
        }
        index = quote + 1;
    }
}

/// Characters end at their closing quote; lifetimes and labels are identifiers.
fn skip_quote(source: &str, start: usize) -> Option<usize> {
    let rest = &source[start + 1..];
    let mut characters = rest.char_indices();
    let (_, first) = characters.next()?;
    if first == '\\' {
        // Skip the escaped character itself (`'\''`), then find the closing quote.
        let close = rest.get(2..)?.find('\'')?;
        return Some(start + 1 + 2 + close + 1);
    }
    match characters.next() {
        Some((offset, '\'')) => Some(start + 1 + offset + 1),
        _ => Some(start + 1),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const PROGRAM: &str = "use tsrust_runtime::tsrust_native_json;\n\
struct Record0 { field0: i64 }\n\
fn function0(value: i64) -> i64 { value + 1 }\n\
#[inline(never)]\n\
fn tsr_result_function1() -> Result<i64, String> { Ok(function0(1)) }\n\
impl Record0 { fn get(&self) -> i64 { function1(self.field0) } }\n\
fn function1<T: Into<i64>>(value: T) -> i64 { let text = \"}\nfn function9() {\"; let raw = r#\"\n{ fn function8() \"#; let label = 'outer: loop { break 'outer value.into() + text.len() as i64 + raw.len() as i64; }; label }\n\
fn main() { let record = Record0 { field0: 2 }; println!(\"{}\", record.get() + tsr_result_function1().unwrap() + '}' as i64); }\n\
mod after { pub fn helper() {} }\n\
fn function2() {}\n";

    #[test]
    fn generated_functions_move_into_child_modules_with_their_attributes() {
        let partitioned = partition_with(PROGRAM, 1);
        assert!(partitioned.contains("mod tsrust_generated_unit0 { use super::*;\npub(super) fn function0("));
        assert!(partitioned.contains("#[inline(never)]\npub(super) fn tsr_result_function1("));
        assert!(partitioned.contains("pub(super) fn function1<T"));
        assert!(partitioned.contains("use tsrust_generated_unit0::*;"));
        // Root items, main and items after the first module stay in place.
        assert!(partitioned.contains("\nstruct Record0 {"));
        assert!(partitioned.contains("\nfn main() {"));
        assert!(partitioned.contains("mod after { pub fn helper() {} }\nfn function2() {}"));
        assert!(!partitioned.contains("pub(super) fn function9") && !partitioned.contains("pub(super) fn function8"));
        // Literal and label text is preserved exactly.
        assert!(partitioned.contains("\"}\nfn function9() {\""));
        assert!(partitioned.contains("r#\"\n{ fn function8() \"#"));
    }

    #[test]
    fn units_follow_the_byte_budget_and_large_budgets_use_one_unit() {
        assert_eq!(partition_with(PROGRAM, usize::MAX).matches("mod tsrust_generated_unit").count(), 1);
        assert_eq!(partition_with(PROGRAM, 1).matches("mod tsrust_generated_unit").count(), 3);
    }

    #[test]
    fn unbalanced_or_function_free_sources_are_unchanged() {
        for source in ["fn function0() {", "struct Record0;\nfn main() {}\n", ""] {
            assert_eq!(partition(source), source);
        }
    }

    #[test]
    fn literals_comments_and_lifetimes_do_not_change_depth() {
        let source = "fn function0<'a>(x: &'a str) -> char { /* { /* nested } */ ( */ // }\n let _ = b'{'; let _ = b\"}\"; let _ = br##\"\"#}\"##; let _ = '\\''; let _ = '\\u{7B}'; '{' }\nfn function1() {}\n";
        let starts = top_level_line_starts(source).unwrap();
        assert_eq!(starts.len(), 2);
        assert!(source[starts[1]..].starts_with("fn function1"));
    }
}
